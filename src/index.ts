import { defineExtension, useDisposable } from 'reactive-vscode'
import { version } from '../package.json'
import { useAnnoPulseCodeLens } from './composables/use-annopulse-codelens'
import { useAnnoPulseCommands } from './composables/use-annopulse-commands'
import { useAnnoPulseDiagnostics } from './composables/use-annopulse-diagnostics'
import { useAnnoPulseExplorer } from './composables/use-annopulse-explorer'
import { useAnnoPulseGit } from './composables/use-annopulse-git'
import { useAnnoPulseHighlight } from './composables/use-annopulse-highlight'
import { useAnnoPulseHover } from './composables/use-annopulse-hover'
import { useAnnoPulseLanguageModelTools } from './composables/use-annopulse-language-model-tools'
import { useAnnoPulseNotebook } from './composables/use-annopulse-notebook'
import { useAnnoPulseSourceControl } from './composables/use-annopulse-source-control'
import { useWorkspaceScan } from './composables/use-workspace-scan'
import { createChangedUriIndex } from './core/git/changed-uri-index'
import { logger } from './utils/logger'

/**
 * VS Code extension lifecycle hooks generated by reactive-vscode.
 */
const { activate, deactivate } = defineExtension(context => {
  useAnnoPulseCommands(context.workspaceState)
  useAnnoPulseDiagnostics()
  const annopulseGit = useAnnoPulseGit()
  const changedUriIndex = createChangedUriIndex(annopulseGit)
  useDisposable(changedUriIndex)
  useAnnoPulseExplorer(annopulseGit, changedUriIndex)
  useWorkspaceScan()
  const annopulseHighlight = useAnnoPulseHighlight()
  useAnnoPulseNotebook(annopulseHighlight.scanTextDocument)
  useAnnoPulseHover(annopulseGit.getMetadata)
  useAnnoPulseSourceControl(changedUriIndex)
  useAnnoPulseCodeLens()
  useAnnoPulseLanguageModelTools()

  logger.info(`✅ Activated, version: ${version} `)
})

export { activate, deactivate }
